// ==================== 交付物类型 ====================

/**
 * 6 种交付物类型。一个任务通常产出多种类型的组合。
 *
 * - ui:       界面 — 用户可见的视觉产出（组件、页面、弹窗）
 * - logic:    逻辑 — 业务规则、算法、流程控制
 * - data:     数据 — 数据模型变更（新表、字段、migration）
 * - api:      接口 — 系统边界上的通信端点
 * - infra:    基建 — 不改功能、改运行方式（部署、配置、性能）
 * - analysis: 分析 — 产出是信息而非代码（调研、方案、选型）
 */
export type DeliverableType = 'ui' | 'logic' | 'data' | 'api' | 'infra' | 'analysis';

/** 中文标签，用于 UI 展示 */
export const DELIVERABLE_LABELS: Record<DeliverableType, string> = {
  ui: '界面',
  logic: '逻辑',
  data: '数据',
  api: '接口',
  infra: '基建',
  analysis: '分析',
};

// ==================== 推断结果 ====================

/**
 * AI 对一个任务交付物的推断结果。
 * 由 Phase 1 生成，Phase 2 确认或修正。
 */
export interface DeliverableInference {
  /** 推断出的交付物类型组合（至少一个） */
  types: DeliverableType[];

  /**
   * 推断置信度
   * - high:   信号词明确命中，上下文充分
   * - medium: 部分推断，可能需要确认
   * - low:    信息不足，需要 Phase 2 追问
   */
  confidence: 'high' | 'medium' | 'low';

  /** 一句话说明推断依据 */
  summary: string;
}

