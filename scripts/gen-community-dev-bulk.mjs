function pad(n, w) {
  return String(n).padStart(w, "0");
}

function buildAssistants(count) {
  const items = [];
  for (let i = 1; i <= count; i++) {
    const topic = ASSIST_TOPICS_ZH[(i - 1) % ASSIST_TOPICS_ZH.length];
    const cat = ASSIST_CATS[i % ASSIST_CATS.length];
    const icon = ICONS[i % ICONS.length];
    const id = `pp-dev-assistant-${pad(i, 4)}`;
    const title = `${topic}助手（模板 #${i}）`;
    const titleEn = `${topic} assistant (template #${i})`;
    items.push({
      id,
      identifier: id,
      title,
      titleEn,
      description: `围绕「${topic}」给出结构化要点与可执行建议；信息不足时先提问。此为开发环境展示用模板，非第三方社区原文。`,
      descriptionEn: `Structured notes and actionable suggestions for “${topic}”; ask if context is missing. Dev demo template, not third-party text.`,
      tags: ["模板", "开发环境", topic.slice(0, 8)],
      tagsEn: ["template", "dev", "demo"],
      icon,
      systemPrompt: `你是工程协作助手，主题为「${topic}」。根据用户提供的材料给出分条建议；标注假设与待核实项；不要编造不存在的路径或链接。使用用户语言回复。`,
      systemPromptEn: `You assist with engineering topics around “${topic}”. Give bullet recommendations; label assumptions and unknowns; do not invent paths or URLs. Reply in the user’s language.`,
      capabilities: {
        bash: i % 3 === 0,
        fileAccess: true,
        web: i % 2 === 0,
        subAgent: false,
        skipReview: false,
        todoRead: false,
        exposePromptPath: true,
        dataStore: false,
      },
      skillIds: [],
      author: "ProjectPilot Dev Templates",
      userName: "pp-dev-templates",
      category: cat,
      createdAt: "2026-01-01T00:00:00.000Z",
      updatedAt: `2026-04-${pad((i % 28) + 1, 2)}T12:00:00.000Z`,
      forkCount: (i * 7) % 200,
      pluginCount: 0,
      knowledgeCount: 0,
      tokenUsage: 1024 + (i % 8) * 256,
    });
  }
  return items;
}

function buildSkills(count) {
  const items = [];
  for (let i = 1; i <= count; i++) {
    const topic = SKILL_TOPICS[(i - 1) % SKILL_TOPICS.length];
    const cat = ASSIST_CATS[i % ASSIST_CATS.length];
    const id = `pp-dev-skill-${pad(i, 4)}`;
    const dirName = `pp-dev-${topic}-${pad(i, 4)}`;
    const name = dirName;
    const md = `---\nname: ${name}\ndescription: 开发环境 Skill 模板：${topic}\n---\n\n## 何时启用\n用户提到 ${topic} 相关产出或需要一段可粘贴的说明/清单时。\n\n## 输出要求\n- 用 Markdown，步骤编号。\n- 缺信息时列出最少追问项。\n- 不声称已与生产配置对齐。\n`;
    const mdEn = `---\nname: ${name}\ndescription: Dev Skill template: ${topic}\n---\n\n## When to use\nWhen the user asks for ${topic}-related output or a paste-ready checklist.\n\n## Output\n- Markdown with numbered steps.\n- List minimal follow-up questions if context is missing.\n- Do not claim production parity.\n`;
    items.push({
      id,
      identifier: id,
      title: `Skill 模板：${topic} #${i}`,
      titleEn: `Skill template: ${topic} #${i}`,
      description: `围绕「${topic}」生成简短步骤或清单（开发环境展示用）。`,
      descriptionEn: `Short steps or checklist for “${topic}” (dev demo).`,
      tags: ["Skill", "模板"],
      tagsEn: ["Skill", "template"],
      category: cat,
      updatedAt: `2026-04-${pad((i % 28) + 1, 2)}T10:00:00.000Z`,
      dirName,
      skillMarkdown: md,
      skillMarkdownEn: mdEn,
      sourceNote:
        "**来源**：由本仓库脚本 `scripts/gen-community-dev-bulk.mjs` 批量生成的开发环境展示模板；非外部社区搬运。未配置 `sourceUrl` 时不提供外链。",
      sourceNoteEn:
        "**Source**: bulk-generated dev demo from `scripts/gen-community-dev-bulk.mjs` in this repo; not imported from a third-party marketplace. No `sourceUrl` unless you add one in remote catalog JSON.",
    });
  }
  return items;
}

